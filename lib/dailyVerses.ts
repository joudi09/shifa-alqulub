// نختار آية اليوم بناءً على التاريخ
export function getDailyVerse(): DailyVerse {
  const today = new Date();
  const startDate = new Date(2025, 0, 1); // 1 يناير 2025 كنقطة بداية
  const daysPassed = Math.floor(
    (today.getTime() - startDate.getTime()) / (1000 * 60 * 60 * 24)
  );
  const index = daysPassed % dailyVerses.length;
  return dailyVerses[index];
}

// نتحقق إذا وصل وقت الإشعار (9 صباحاً)
export function shouldSendDailyVerse(): boolean {
  const now = new Date();
  return now.getHours() === 9 && now.getMinutes() < 5;
}

// نتحقق إذا أرسلنا آية اليوم
export function wasVerseSentToday(): boolean {
  const today = new Date().toDateString();
  return localStorage.getItem(`verse_notif_${today}`) === "sent";
}

// نحفظ إننا أرسلنا آية اليوم
export function markVerseSent(): void {
  const today = new Date().toDateString();
  localStorage.setItem(`verse_notif_${today}`, "sent");
}